<pre><code>import 'dart:io';
import 'dart:convert';

class Task {
  final int id;
  String title;
  bool completed;
  final DateTime createdAt;

  Task({required this.id, required this.title, this.completed = false, DateTime? createdAt})
      : createdAt = createdAt ?? DateTime.now();

  factory Task.fromJson(Map&lt;String, dynamic&gt; j) =&gt; Task(
    id: j['id'],
    title: j['title'],
    completed: j['completed'] ?? false,
    createdAt: DateTime.parse(j['created_at']),
  );

  Map&lt;String, dynamic&gt; toJson() =&gt; {
    'id': id,
    'title': title,
    'completed': completed,
    'created_at': createdAt.toIso8601String(),
  };

  @override
  String toString() {
    var status = completed ? '✓' : '○';
    var date = '$${createdAt.month}/$${createdAt.day}';
    return '[$status] #$id $title ($date)';
  }
}

class TodoRepository {
  final String _path;
  List&lt;Task&gt; _tasks = [];

  TodoRepository([this._path = 'todos.json']);

  void load() {
    var file = File(_path);
    if (file.existsSync()) {
      var data = jsonDecode(file.readAsStringSync()) as List;
      _tasks = data.map((j) =&gt; Task.fromJson(j)).toList();
    }
  }

  void _save() =&gt; File(_path).writeAsStringSync(
      JsonEncoder.withIndent('  ').convert(_tasks.map((t) =&gt; t.toJson()).toList()));

  Task add(String title) {
    var id = _tasks.isEmpty ? 1 : _tasks.map((t) =&gt; t.id).reduce((a, b) =&gt; a &gt; b ? a : b) + 1;
    var task = Task(id: id, title: title);
    _tasks.add(task);
    _save();
    return task;
  }

  List&lt;Task&gt; getAll({bool? completed}) =&gt;
      completed == null ? _tasks : _tasks.where((t) =&gt; t.completed == completed).toList();

  bool complete(int id) {
    var task = _tasks.cast&lt;Task?&gt;().firstWhere((t) =&gt; t?.id == id, orElse: () =&gt; null);
    if (task == null) return false;
    task.completed = true;
    _save();
    return true;
  }

  bool delete(int id) {
    var before = _tasks.length;
    _tasks.removeWhere((t) =&gt; t.id == id);
    if (_tasks.length &lt; before) { _save(); return true; }
    return false;
  }

  void clearCompleted() {
    _tasks.removeWhere((t) =&gt; t.completed);
    _save();
  }
}

