    var b = parseNumber(parts[2]);
    if (a == null || b == null) {
      print('Invalid numbers: $${parts[0]}, $${parts[2]}');
      continue;
    }

    try {
      var result = calc.calculate(a, parts[1], b);
      print('Result: $${result % 1 == 0 ? result.toInt() : result}');
    } on ArgumentError catch (e) {
      print('Error: $${e.message}');
    }
  }
