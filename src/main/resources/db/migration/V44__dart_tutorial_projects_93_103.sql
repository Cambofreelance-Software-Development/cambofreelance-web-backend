  show(100,  TempUnit.celsius,    TempUnit.fahrenheit); // 100°C = 212.00°F
  show(32,   TempUnit.fahrenheit, TempUnit.celsius);    // 32°F = 0.00°C
  show(300,  TempUnit.kelvin,     TempUnit.celsius);    // 300K = 26.85°C
