    if (!f.existsSync()) return;
    var data = jsonDecode(f.readAsStringSync()) as Map;
    _nextId = data['nextId'] ?? 1;
    for (var j in (data['contacts'] as List)) {
      var c = Contact.fromJson(j);
      _contacts[c.id] = c;
    }
    print('Loaded $${_contacts.length} contacts');
  }

  void save() {
    File(_dbPath).writeAsStringSync(JsonEncoder.withIndent('  ').convert({
      'nextId': _nextId,
      'contacts': _contacts.values.map((c) =&gt; c.toJson()).toList(),
    }));
  }

  Contact add({required String name, required String email, required String phone,
               String? company, List&lt;String&gt;? tags}) {
    var c = Contact(id: 'C$${_nextId++}', name: name, email: email,
                    phone: phone, company: company, tags: tags);
    _contacts[c.id] = c;
    save();
    return c;
  }

  List&lt;Contact&gt; search(String query) =&gt;
      _contacts.values.where((c) =&gt; c.matches(query)).toList()
